package lint

import (
	"bufio"
	"fmt"
	"path/filepath"
	"strings"

	"edith-engine/internal/store"
	"edith-engine/internal/vault"
)

type FindingSeverity string

const (
	SeverityError   FindingSeverity = "ERROR"
	SeverityWarning FindingSeverity = "WARNING"
	SeverityInfo    FindingSeverity = "INFO"
)

type FindingCategory string

const (
	CategoryBrokenLink      FindingCategory = "broken_link"
	CategoryOrphanNote      FindingCategory = "orphan_note"
	CategorySuspiciousTitle FindingCategory = "suspicious_title"
	CategoryDuplicate       FindingCategory = "duplicate_candidate"
	CategoryMissingSource   FindingCategory = "missing_source_ref"
	CategoryStaleIndex      FindingCategory = "stale_index"
	CategoryUnindexed       FindingCategory = "unindexed_change"
)

// Finding represents a single linting or knowledge-maintenance issue.
type Finding struct {
	Category   FindingCategory `json:"category"`
	Severity   FindingSeverity `json:"severity"`
	Path       string          `json:"path"`
	LineNumber int             `json:"line_number,omitempty"`
	Message    string          `json:"message"`
	Details    string          `json:"details,omitempty"`
}

// Report contains all findings generated by the knowledge maintenance suite.
type Report struct {
	Findings      []Finding `json:"findings"`
	TotalErrors   int       `json:"total_errors"`
	TotalWarnings int       `json:"total_warnings"`
	TotalInfo     int       `json:"total_info"`
}

// Linter performs deterministic health checks across vault notes and index state.
type Linter struct {
	vaultRoot string
	scanner   *vault.Scanner
	reader    *vault.Reader
	db        *store.DB
}

// NewLinter constructs a new Linter.
func NewLinter(vaultRoot string, db *store.DB) (*Linter, error) {
	scanner, err := vault.NewScanner(vaultRoot)
	if err != nil {
		return nil, fmt.Errorf("failed to init scanner: %w", err)
	}
	reader, err := vault.NewReader(vaultRoot)
	if err != nil {
		return nil, fmt.Errorf("failed to init reader: %w", err)
	}

	return &Linter{
		vaultRoot: vaultRoot,
		scanner:   scanner,
		reader:    reader,
		db:        db,
	}, nil
}

// Run executes all knowledge maintenance checks and compiles a comprehensive Report.
func (l *Linter) Run() (*Report, error) {
	paths, err := l.scanner.Scan()
	if err != nil {
		return nil, fmt.Errorf("failed scanning vault: %w", err)
	}

	report := &Report{
		Findings: make([]Finding, 0),
	}

	notesMap := make(map[string]*vault.Note)
	baseNameToPaths := make(map[string][]string)
	inboundLinkCount := make(map[string]int)

	// Read and parse all notes
	for _, p := range paths {
		note, err := l.reader.ReadNote(p)
		if err != nil {
			report.add(Finding{
				Category: CategoryUnindexed,
				Severity: SeverityError,
				Path:     p,
				Message:  fmt.Sprintf("Failed to read note: %v", err),
			})
			continue
		}
		notesMap[p] = note
		base := strings.ToLower(strings.TrimSuffix(filepath.Base(p), filepath.Ext(p)))
		baseNameToPaths[base] = append(baseNameToPaths[base], p)
		inboundLinkCount[p] = 0
	}

	// 1. Broken Links & Inbound Link Tracking
	for _, note := range notesMap {
		for _, link := range note.Links {
			if link.IsExternal {
				continue
			}

			resolvedPath := resolveLink(link, notesMap, baseNameToPaths)
			if resolvedPath != "" {
				inboundLinkCount[resolvedPath]++
			} else if isInstructionalSyntaxLink(link, note) {
				report.add(Finding{
					Category:   CategoryBrokenLink,
					Severity:   SeverityInfo,
					Path:       note.Metadata.RelPath,
					LineNumber: link.LineNumber,
					Message:    fmt.Sprintf("Instructional syntax reference: [[%s]] (not treated as broken link)", link.RawTarget),
					Details:    fmt.Sprintf("Raw target: %s", link.RawTarget),
				})
			} else if isWelcomePlaceholderLink(link, note) {
				report.add(Finding{
					Category:   CategoryBrokenLink,
					Severity:   SeverityInfo,
					Path:       note.Metadata.RelPath,
					LineNumber: link.LineNumber,
					Message:    fmt.Sprintf("Starter placeholder link in welcome note: [[%s]] (not treated as broken link)", link.RawTarget),
					Details:    fmt.Sprintf("Raw target: %s", link.RawTarget),
				})
			} else {
				// Broken internal link
				report.add(Finding{
					Category:   CategoryBrokenLink,
					Severity:   SeverityError,
					Path:       note.Metadata.RelPath,
					LineNumber: link.LineNumber,
					Message:    fmt.Sprintf("Broken internal link: [[%s]] target not found", link.RawTarget),
					Details:    fmt.Sprintf("Raw target: %s", link.RawTarget),
				})
			}
		}
	}

	// 2. Orphan Notes
	for _, p := range paths {
		if inboundLinkCount[p] == 0 {
			// Check if known entrypoint
			if isEntrypointNote(p) {
				report.add(Finding{
					Category: CategoryOrphanNote,
					Severity: SeverityInfo,
					Path:     p,
					Message:  "Root or entry point note with no inbound links",
				})
			} else {
				report.add(Finding{
					Category: CategoryOrphanNote,
					Severity: SeverityWarning,
					Path:     p,
					Message:  "Orphan note: no inbound links from any other note in vault",
				})
			}
		}
	}

	// 3. Missing or Suspicious Titles
	for _, note := range notesMap {
		t := strings.TrimSpace(note.Metadata.Title)
		base := strings.TrimSuffix(filepath.Base(note.Metadata.RelPath), filepath.Ext(note.Metadata.RelPath))

		if t == "" || t == "Untitled" {
			report.add(Finding{
				Category: CategorySuspiciousTitle,
				Severity: SeverityWarning,
				Path:     note.Metadata.RelPath,
				Message:  "Missing title: note lacks a markdown heading or title property",
			})
		} else if (t == "README" || t == "index") && !strings.Contains(note.Metadata.RelPath, "/") {
			// Top-level README or index without descriptive title
			report.add(Finding{
				Category: CategorySuspiciousTitle,
				Severity: SeverityInfo,
				Path:     note.Metadata.RelPath,
				Message:  fmt.Sprintf("Generic title %q: consider adding a descriptive H1 heading", t),
			})
		} else if t == base && !strings.HasPrefix(note.Content, "#") {
			// Title fell back to filename because no heading was present
			report.add(Finding{
				Category: CategorySuspiciousTitle,
				Severity: SeverityInfo,
				Path:     note.Metadata.RelPath,
				Message:  fmt.Sprintf("Title inferred from filename %q; no explicit H1 found", t),
			})
		}
	}

	// 4. Duplicate Candidates (Exact content & Similar titles)
	contentHashToPaths := make(map[string][]string)
	titleToPaths := make(map[string][]string)

	for _, note := range notesMap {
		contentHashToPaths[note.Metadata.ContentHash] = append(contentHashToPaths[note.Metadata.ContentHash], note.Metadata.RelPath)
		normTitle := strings.ToLower(strings.TrimSpace(note.Metadata.Title))
		if normTitle != "" && normTitle != "readme" && normTitle != "index" {
			titleToPaths[normTitle] = append(titleToPaths[normTitle], note.Metadata.RelPath)
		}
	}

	for hash, dupePaths := range contentHashToPaths {
		if len(dupePaths) > 1 {
			report.add(Finding{
				Category: CategoryDuplicate,
				Severity: SeverityWarning,
				Path:     dupePaths[0],
				Message:  fmt.Sprintf("Candidate exact duplicate content detected across %d notes", len(dupePaths)),
				Details:  fmt.Sprintf("Matches: %s (hash: %s)", strings.Join(dupePaths, ", "), hash[:12]),
			})
		}
	}

	for title, dupePaths := range titleToPaths {
		if len(dupePaths) > 1 {
			report.add(Finding{
				Category: CategoryDuplicate,
				Severity: SeverityInfo,
				Path:     dupePaths[0],
				Message:  fmt.Sprintf("Candidate duplicate title %q shared across %d notes", title, len(dupePaths)),
				Details:  fmt.Sprintf("Notes: %s", strings.Join(dupePaths, ", ")),
			})
		}
	}

	// 5. Missing Source References in 03-Wiki Notes
	for _, note := range notesMap {
		if strings.HasPrefix(note.Metadata.RelPath, "03-Wiki/") {
			base := filepath.Base(note.Metadata.RelPath)
			if base == "README.md" || base == "index.md" {
				continue
			}

			hasSourceRef := false
			for _, l := range note.Links {
				if l.IsExternal || strings.HasPrefix(l.CleanTarget, "02-Raw-Sources/") {
					hasSourceRef = true
					break
				}
			}

			if !hasSourceRef {
				report.add(Finding{
					Category: CategoryMissingSource,
					Severity: SeverityInfo,
					Path:     note.Metadata.RelPath,
					Message:  "Wiki note has no links to raw sources (02-Raw-Sources/) or citations",
				})
			}
		}
	}

	// 6 & 7. Database synchronization checks (Stale index & unindexed changes)
	if l.db != nil {
		dbNotes, err := l.db.ListAllNotes()
		if err == nil {
			diskSet := make(map[string]bool)
			for _, p := range paths {
				diskSet[p] = true
			}

			dbMap := make(map[string]*store.IndexedNote)
			for _, dn := range dbNotes {
				dbMap[dn.RelPath] = dn
				if !diskSet[dn.RelPath] {
					report.add(Finding{
						Category: CategoryStaleIndex,
						Severity: SeverityWarning,
						Path:     dn.RelPath,
						Message:  "Stale index entry: note exists in database but is missing from vault",
					})
				}
			}

			for _, p := range paths {
				note := notesMap[p]
				if note == nil {
					continue
				}
				dn, exists := dbMap[p]
				if !exists {
					report.add(Finding{
						Category: CategoryUnindexed,
						Severity: SeverityInfo,
						Path:     p,
						Message:  "Unindexed note: not yet indexed in SQLite database",
					})
				} else if dn.ContentHash != note.Metadata.ContentHash {
					report.add(Finding{
						Category: CategoryUnindexed,
						Severity: SeverityInfo,
						Path:     p,
						Message:  "Note modified on disk since last database indexing",
					})
				}
			}
		}
	}

	return report, nil
}

func (r *Report) add(f Finding) {
	switch f.Severity {
	case SeverityError:
		r.TotalErrors++
	case SeverityWarning:
		r.TotalWarnings++
	case SeverityInfo:
		r.TotalInfo++
	}
	r.Findings = append(r.Findings, f)
}

func resolveLink(link vault.Link, notesMap map[string]*vault.Note, baseNameToPaths map[string][]string) string {
	target := link.CleanTarget

	// 1. Direct path match
	if _, ok := notesMap[target]; ok {
		return target
	}
	if _, ok := notesMap[target+".md"]; ok {
		return target + ".md"
	}

	// 2. Base filename match (Obsidian allows [[Note-Name]] without folder)
	base := strings.ToLower(filepath.Base(target))
	base = strings.TrimSuffix(base, ".md")
	if paths, ok := baseNameToPaths[base]; ok && len(paths) > 0 {
		return paths[0]
	}

	return ""
}

func isEntrypointNote(relPath string) bool {
	clean := filepath.ToSlash(relPath)
	return clean == "README.md" ||
		clean == "Edith/Welcome.md" ||
		clean == "03-Wiki/index.md" ||
		clean == "00-System/Edith-Protocol.md" ||
		clean == "00-System/Edith-Architecture.md" ||
		clean == "12-Logs/log.md" ||
		strings.HasSuffix(clean, "/README.md")
}

func isInstructionalSyntaxLink(link vault.Link, note *vault.Note) bool {
	if !link.IsWikiLink {
		return false
	}
	normTarget := strings.ToLower(strings.TrimSpace(link.CleanTarget))
	if normTarget != "wikilinks" && normTarget != "wikilink" {
		return false
	}

	line := getLine(note.Content, link.LineNumber)
	lowerLine := strings.ToLower(line)
	cleanPath := filepath.ToSlash(note.Metadata.RelPath)

	// Contextual indicators of link syntax discussion
	isSystemDoc := strings.HasPrefix(cleanPath, "00-System/") || strings.Contains(strings.ToLower(cleanPath), "protocol")
	hasSyntaxKeyword := strings.Contains(lowerLine, "obsidian") ||
		strings.Contains(lowerLine, "syntax") ||
		strings.Contains(lowerLine, "format") ||
		strings.Contains(lowerLine, "using") ||
		strings.Contains(lowerLine, "e.g.") ||
		strings.Contains(lowerLine, "example")

	return isSystemDoc || hasSyntaxKeyword
}

func isWelcomePlaceholderLink(link vault.Link, note *vault.Note) bool {
	if !link.IsWikiLink {
		return false
	}
	cleanPath := filepath.ToSlash(note.Metadata.RelPath)
	isWelcome := cleanPath == "Edith/Welcome.md" ||
		cleanPath == "Welcome.md" ||
		strings.HasSuffix(cleanPath, "/Welcome.md") ||
		strings.Contains(note.Content, "This is your new *vault*")

	if !isWelcome {
		return false
	}

	normTarget := strings.ToLower(strings.TrimSpace(link.CleanTarget))
	return normTarget == "create a link" || normTarget == "placeholder"
}

func getLine(content string, lineNum int) string {
	scanner := bufio.NewScanner(strings.NewReader(content))
	current := 0
	for scanner.Scan() {
		current++
		if current == lineNum {
			return scanner.Text()
		}
	}
	return ""
}
